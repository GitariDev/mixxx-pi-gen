// Acceptance I, X2 (mixxx-quit-library-widget.patch): Ctrl+Q with a drive
// loaded must not reach the skin's deleted WLibrary. Based on the
// investigation's fixture (INVESTIGATION-X1-X2.md, x2_uaf.cpp).
//
// Mixxx's quit order: MixxxMainWindow deletes the skin first
// (mixxxmainwindow.cpp, "deleting skin": setCentralWidget(nullptr), then
// sendPostedEvents(DeferredDelete)). CoreServices then deletes PlayerManager
// before Library, so each deck and pad with a track unloads it
// (~BaseTrackPlayerImpl -> unloadTrack() -> PlayerInfo::setTrackInfo(group,
// null)) and PlayerInfo emits trackChanged while MixpiMedia (a child of
// Library) is still alive. Its hook runs refresh(), which looks up the skin
// root through Library's parent lambda: mixpiSkinRoot(m_parent()).
//
// The shipped mixpiSkinRoot (widget/mixpipage.h), MixpiMediaPage,
// MixpiBottomStrip and mixpiSetNamedLabelText (library/mixpimediapage.h) are
// used as they are. Library's widget member and its parent lambda come from
// the stack under test (quit_library_widget_member.h, generated by the runner
// from src/library/library.h and library.cpp). WLibrary is a stand-in
// QStackedWidget, as the real one is.
//
// The stand-in WLibrary records each address it is deleted from and keeps its
// memory, filled with 0xDE, so a use of the deleted widget is found every run:
// in report mode the fixture checks what the lookup returned before using it;
// in use mode it makes the lookup as refresh() does, which faults.
//
// usage: quit-library-widget-test [report|use]
#include <QApplication>
#include <QLabel>
#include <QMainWindow>
#include <QSet>
#include <QStackedWidget>
#include <cstdlib>
#include <cstring>
#include <iostream>
#include <new>
#include <vector>

#include "library/mixpimediapage.h"

namespace {
int failures = 0;

void check(bool condition, const std::string& message) {
    if (!condition) {
        ++failures;
        std::cout << "FAIL " << message << std::endl;
    } else {
        std::cout << "PASS " << message << std::endl;
    }
}

QSet<const void*>& deletedWidgets() {
    static QSet<const void*> addresses;
    return addresses;
}
} // namespace

class WLibrary : public QStackedWidget {
  public:
    using QStackedWidget::QStackedWidget;
    ~WLibrary() override {
        deletedWidgets().insert(static_cast<const QWidget*>(this));
    }
    static void* operator new(std::size_t size) {
        return std::malloc(size);
    }
    // Keep the freed widget's memory, poisoned, for the rest of the run.
    static void operator delete(void* pointer, std::size_t size) {
        std::memset(pointer, 0xDE, size);
    }
};

#include "quit_library_widget_member.h"

namespace {
// A stand-in for PlayerInfo::trackChanged's receivers.
class PlayerInfoStub : public QObject {
  public:
    std::vector<std::function<void(const QString&)>> receivers;
    void trackChanged(const QString& group) {
        for (const auto& receiver : receivers) {
            receiver(group);
        }
    }
};

MixpiMediaDrive gander(bool loaded) {
    MixpiMediaDrive drive;
    drive.identity = QStringLiteral("identity-GANDER1");
    drive.name = QStringLiteral("GANDER1");
    drive.opened = true;
    drive.rekordbox = true;
    MixpiMediaVolume volume;
    volume.token = QStringLiteral("token-GANDER1");
    volume.label = QStringLiteral("GANDER1");
    volume.path = QStringLiteral("/media/pi/GANDER1");
    volume.opened = true;
    drive.volumes.append(volume);
    if (loaded) {
        for (const auto& group : {QStringLiteral("[Channel1]"), QStringLiteral("[Sampler1]")}) {
            MixpiMediaUser user;
            user.group = group;
            user.title = QStringLiteral("Your Body");
            drive.users.append(user);
        }
    }
    drive.state = loaded ? MixpiMediaState::InUse : MixpiMediaState::Ready;
    return drive;
}
} // namespace

int main(int argc, char** argv) {
    QApplication app(argc, argv);
    const QString mode = argc > 1 ? QString::fromLocal8Bit(argv[1]) : QStringLiteral("report");

    // The main window and the skin: WLibrary and the deck row's USB chip
    // (a Label named MixpiUsbName) inside the skin root.
    auto* main = new QMainWindow;
    auto* skin = new QWidget;
    auto* chip = new QLabel(QStringLiteral("USB"), skin);
    chip->setObjectName(QStringLiteral("MixpiUsbName"));
    main->setCentralWidget(skin);
    main->resize(800, 480);
    main->show();
    QApplication::processEvents();

    // Library::bindLibraryWidget, and MixpiMedia's widgets on the skin root
    // (ensureWidgets: the page and the bottom strip).
    LibraryWidgetHolder library;
    library.m_pLibraryWidget = new WLibrary(skin);
    const auto parent = library.parent();
    QWidget* host = mixpiSkinRoot(parent());
    check(host == skin, "running: the lookup through the library widget finds the skin root");
    QPointer<MixpiMediaPage> page = new MixpiMediaPage(host, [](double) {});
    QPointer<MixpiBottomStrip> strip = new MixpiBottomStrip(host);
    page->open();
    strip->showPing(QStringLiteral("identity-SPARE"), QStringLiteral("SPARE"), QStringLiteral("rekordbox export found"));
    QApplication::processEvents();

    QList<MixpiMediaDrive> drives{gander(true)};
    int refreshes = 0;
    int reachedDeleted = 0;
    // MixpiMedia::refresh(), the part that reaches widgets.
    auto refresh = [&] {
        ++refreshes;
        const auto state = mixpi_media::chipState(drives);
        QWidget* found = parent();
        if (mode == QLatin1String("report") && found && deletedWidgets().contains(found)) {
            ++reachedDeleted;
            std::cout << "USE-AFTER-FREE refresh() reached the deleted WLibrary at " << found << std::endl;
            return;
        }
        mixpiSetNamedLabelText<QLabel>(mixpiSkinRoot(found), QStringLiteral("MixpiUsbName"),
                mixpi_media::chipName(drives));
        if (page) {
            page->setEjectAvailable(true);
            if (page->isVisible()) {
                page->setDrives(drives, {});
            }
            page->setHandover({}, {});
        }
        (void)state;
    };
    PlayerInfoStub playerInfo;
    playerInfo.receivers.push_back([&](const QString&) { refresh(); });

    // While Mixxx runs nothing changes: a load still reaches the chip.
    playerInfo.trackChanged(QStringLiteral("[Channel1]"));
    check(chip->text() == QLatin1String("GANDER1"), "running: a deck load sets the USB chip to GANDER1");
    check(page && page->isVisible(), "running: the Media page is open over the skin");
    check(strip && strip->kind() == MixpiBottomStrip::Kind::Ping, "running: a ping shows on the bottom strip");

    // Ctrl+Q. mixxxmainwindow.cpp: "deleting skin".
    QPointer<QWidget> pSkin(main->centralWidget());
    main->setCentralWidget(nullptr);
    if (!pSkin.isNull()) {
        QCoreApplication::sendPostedEvents(pSkin, QEvent::DeferredDelete);
    }
    check(pSkin.isNull(), "quit: the skin is deleted");
    check(deletedWidgets().size() == 1, "quit: the skin's WLibrary is deleted with it");
    check(page.isNull() && strip.isNull(), "quit: the Media page and the strip go with the skin");

    // The menu bar, the preferences and the config save allocate before
    // PlayerManager goes.
    std::vector<QByteArray> churn;
    for (int index = 0; index < 2000; ++index) {
        churn.emplace_back(64 + (index % 512), char(0xA5));
    }

    // ~PlayerManager: both decks and two pads held tracks from GANDER1.
    drives = {gander(false)};
    std::cout << "UNLOADING" << std::endl;
    for (const char* group : {"[Channel1]", "[Channel2]", "[Sampler1]", "[Sampler2]"}) {
        playerInfo.trackChanged(QString::fromLatin1(group));
    }
    check(refreshes == 5, "quit: each deck and pad unload ran refresh()");
    check(reachedDeleted == 0, "quit: no unload reached the deleted WLibrary");
    check(parent() == nullptr, "quit: the lookup returns no widget once the skin is gone");

    delete main;
    std::cout << failures << " failures" << std::endl;
    return failures == 0 ? 0 : 1;
}
