"""Wave J13: compile the shipped main waveform height rule with real Qt and run each check.

Production code, from the patched stack: waveform/mixpiwaveformgain.h (which
viewers are main waveforms and the gain their height follows, as
WaveformWidgetFactory::createWaveformWidget and
WaveformWidgetRenderer::onPreRender use it) and the control framework
(control, controlobject, controlproxy, controlpotmeter, controlpushbutton,
controlbehavior). The skin is generated by mixpi-performance.py from the
same small Pioneered base as tests/test_performance_skin.py, in both loop
displays ("focus", the card's, and "overlay").

--baseline builds the stack without mixxx-waveform-height.patch; the header is
then absent, every viewer takes total_gain as in stock Mixxx, and the checks
about the main waveforms must fail.
"""
import argparse
import importlib.util
from pathlib import Path
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from native.library_interface_runner import (PATCH_DIR, populate_pinned, qt_flags,
                                             qt_environment, moc_path, reconstruct)
from native.agreed_controls_runner import DOUBLES, PINNED_FILES

ROOT = Path(__file__).resolve().parents[2]
NATIVE = ROOT / 'tests/native'
FILES = ROOT / 'stage3/01-install-packages/files'
PATCH = 'mixxx-waveform-height.patch'
MODES = ('focus', 'overlay')


def load(name):
    spec = importlib.util.spec_from_file_location(name.replace('-', '_'), FILES / (name + '.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generate_skin(folder, loop_display):
    """skin.xml as mixpi-performance.py builds it on a small Pioneered base."""
    skin = Path(folder) / 'Pioneered'
    skin.mkdir(parents=True)
    (skin / 'skin.xml').write_text(
        '<skin><manifest><title>Pioneered</title><description>original</description>'
        '<attributes><attribute config_key="[Master],num_samplers">16</attribute>'
        '</attributes></manifest></skin>')
    (skin / 'style.qss').write_text('/* upstream */\n')
    (skin / 'waveform.xml').write_text(
        '<Template><Visual><ObjectName>Waveform</ObjectName>'
        '<Channel><Variable name="channel"/></Channel><BeatColor>#40ffffff</BeatColor>'
        '<Mark><Control>hotcue_1_position</Control></Mark></Visual></Template>')
    (skin / 'deck.xml').write_text(
        '<Template><Overview><ObjectName>DeckOverview</ObjectName>'
        '<Channel><Variable name="channel"/></Channel><MarkRange>'
        '<StartControl>loop_start_position</StartControl><EndControl>loop_end_position</EndControl>'
        '</MarkRange></Overview></Template>')
    touch = load('pioneered-touch')
    (skin / 'library.xml').write_text(touch.patch_library(
        (ROOT / 'tests/fixtures/pioneered-library.xml').read_text()))
    load('mixpi-performance').build(skin, loop_display)
    return skin / 'skin.xml'


def stack(target, baseline):
    names, _ = reconstruct(target, exclude=(PATCH,) if baseline else ())
    if not baseline and PATCH not in names:
        paths = re.findall(r'^diff --git a/(\S+) b/\S+$', (PATCH_DIR / PATCH).read_text(), re.MULTILINE)
        populate_pinned(target, [path for path in paths if not path.endswith('mixpiwaveformgain.h')])
        subprocess.run(['git', 'apply', str(PATCH_DIR / PATCH)], cwd=target, check=True, timeout=15)
    populate_pinned(target, ['src/' + name for name in PINNED_FILES])
    return names


def build(target, baseline):
    support = target / 'interfaces'
    for name, text in DOUBLES.items():
        (support / name).parent.mkdir(parents=True, exist_ok=True)
        (support / name).write_text(text)
    includes = ['-I' + str(support), '-I' + str(target / 'src'), '-I' + str(NATIVE)]
    for header in ('control/control.h', 'control/controlobject.h', 'control/controlproxy.h',
                   'control/controlpotmeter.h', 'control/controlpushbutton.h'):
        path = target / 'src' / header
        subprocess.run([moc_path(), *includes, str(path),
                        '-o', str(path.parent / ('moc_' + path.stem + '.cpp'))],
                       check=True, timeout=30)
    sources = [target / 'src' / name for name in
               ('preferences/configobject.cpp', 'control/control.cpp', 'control/controlobject.cpp',
                'control/controlproxy.cpp', 'control/controlpotmeter.cpp',
                'control/controlpushbutton.cpp', 'control/controlbehavior.cpp')]
    binary = target / 'waveform-height-test'
    command = ['c++', '-std=c++20', '-Wall', '-Wextra', *includes,
               *(['-DMIXPI_WAVEFORM_HEIGHT_BASELINE=1'] if baseline else []),
               *[str(source) for source in sources],
               str(NATIVE / 'waveform_height_test.cpp'), '-o', str(binary),
               '-pthread', *qt_flags(('QtCore', 'QtGui', 'QtWidgets', 'QtXml'))]
    print('COMPILE', repr(command), flush=True)
    subprocess.run(command, check=True, timeout=600)
    return binary


def run(modes=MODES, baseline=False):
    """One CompletedProcess per loop display, in the order given."""
    with tempfile.TemporaryDirectory(prefix='mixpi-waveform-height-') as temporary:
        target = Path(temporary) / 'build'
        target.mkdir()
        names = stack(target, baseline)
        print('PATCHES', len(names), 'BASELINE' if baseline else PATCH, flush=True)
        binary = build(target, baseline)
        results = []
        for mode in modes:
            skin = generate_skin(Path(temporary) / 'skin' / mode, mode)
            result = subprocess.run([str(binary), str(skin), mode], env=qt_environment(),
                                    capture_output=True, text=True, timeout=120)
            print('MODE', mode, 'RC', result.returncode, result.stdout, result.stderr[-4000:], flush=True)
            results.append(result)
        return results


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('modes', nargs='*')
    parser.add_argument('--baseline', action='store_true')
    options = parser.parse_args()
    raise SystemExit(max(result.returncode
                         for result in run(options.modes or list(MODES), options.baseline)))
